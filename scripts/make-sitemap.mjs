// Regenerates public/sitemap.xml: every static route plus the service, project, news and careers slugs
// read from src/data, each as an English URL and its /ar mirror with hreflang alternates.
// Usage: node scripts/make-sitemap.mjs [origin]   (default origin: the placeholder https://gridnova.example)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const origin = (process.argv[2] ?? "https://gridnova.example").replace(/\/$/, "");
const read = (p) => fs.readFileSync(path.join(root, p), "utf8");
const slugs = (file, key) => [...new Set([...read(file).matchAll(new RegExp(`^\\s*${key}: "([^"]+)",`, "gm"))].map((m) => m[1]))];

const routes = [
  "/",
  "/services",
  ...slugs("src/data/services.ts", "slug").map((s) => `/services/${s}`),
  "/projects",
  ...slugs("src/data/projects.ts", "slug").map((s) => `/projects/${s}`),
  "/about",
  "/news",
  ...slugs("src/data/news.ts", "slug").map((s) => `/news/${s}`),
  "/contact",
  "/careers",
  ...slugs("src/data/careers.ts", "id").map((s) => `/careers/${s}`),
  "/careers/apply",
  "/faq",
  "/privacy",
  "/terms",
  "/cookies",
];

const ar = (r) => (r === "/" ? "/ar" : `/ar${r}`);
const entry = (loc, en, arPath) =>
  `  <url><loc>${origin}${loc}</loc><xhtml:link rel="alternate" hreflang="en" href="${origin}${en}"/><xhtml:link rel="alternate" hreflang="ar" href="${origin}${arPath}"/></url>`;

const xml = [
  '<?xml version="1.0" encoding="UTF-8"?>',
  `<!-- Generated by scripts/make-sitemap.mjs — ${routes.length} routes × EN + AR. Pass the production origin as the first argument before launch. -->`,
  '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">',
  ...routes.flatMap((r) => [entry(r, r, ar(r)), entry(ar(r), r, ar(r))]),
  "</urlset>",
  "",
].join("\n");

fs.writeFileSync(path.join(root, "public/sitemap.xml"), xml);
console.log(`sitemap: ${routes.length} routes, ${routes.length * 2} URLs → public/sitemap.xml`);
